"""Hand-written loot specs for each farm. tools/build_loot.py turns these into Loot.lua.

Per farm:
  mobs   NPC names as in the Classic database. Levels, elite status and drop rates are looked up.
  kph    kills per hour, worked out from the mobs' spawn points (tools/kills.py: about 100 where
         spawns are plentiful, fewer for small camps, at most 50 for elites). Only farms marked
         fixed=True (group runs, AoE farms, dungeons, Devilsaurs) keep the kph written here; for
         the rest it's only a fallback when the mobs have no spawn data.
  diff   difficulty 1-5 (editorial).
  items  (item name, fallback %, qty per drop[, opts]). The drop % comes from CMaNGOS/Wowhead
         data for the listed mobs when it exists; the fallback % is only used when it doesn't,
         and is marked as an estimate in game. opts: prof="Skinning" (only counts if you have it).
  how / notes  shown in the detail panel.
Fishing farms use `fishing` instead of mobs/items: pool tier from pools.csv and pools per hour.
"""



def skin(tier, rate=1.0):
    """Skinning yield per kill (estimates; skinning loot isn't in the drop tables)."""
    S = "Skinning"
    t = {
        "light":  [("Light Leather", 100 * rate, 1, S), ("Ruined Leather Scraps", 40 * rate, 1, S), ("Light Hide", 3 * rate, 1, S)],
        "medium": [("Medium Leather", 100 * rate, 1, S), ("Light Leather", 20 * rate, 1, S), ("Medium Hide", 3 * rate, 1, S)],
        "heavy":  [("Heavy Leather", 100 * rate, 1, S), ("Medium Leather", 20 * rate, 1, S), ("Heavy Hide", 3 * rate, 1, S)],
        "thick":  [("Thick Leather", 100 * rate, 1, S), ("Heavy Leather", 15 * rate, 1, S), ("Thick Hide", 3 * rate, 1, S)],
        "rugged": [("Rugged Leather", 100 * rate, 1, S), ("Thick Leather", 15 * rate, 1, S), ("Rugged Hide", 3 * rate, 1, S)],
    }
    return [dict(name=n, est=p, qty=q, prof=pr, skin=True) for n, p, q, pr in t[tier]]


def I(name, est, qty=1.0):
    return dict(name=name, est=est, qty=qty)


