"""Build DropIndex.lua: which mobs drop every AH-tradeable item, for the live farm finder.

Usage:
    python tools/build_drops.py

Keeps tradeable (bind none / on equip), non-grey items from the WoW Forever client tables and
their mob sources from CMaNGOS classic-db and Wowhead data (see classicdb.py), with a drop chance
of at least MIN_PCT. Left out: bosses, rares, faction NPCs, unique named NPCs (fewer than
MIN_SPAWNS spawn points), dungeon/raid/battleground mobs, and rates of 95%+ or exactly 80%, which
in this data are vendor stock or quest-objective artefacts rather than real drop rates. Output:
    ns.drops.items[itemID] = { name, quality, npcID, chance x100, npcID, chance x100, ... }
    ns.drops.npcs[npcID]   = { name, minLevel, maxLevel, elite (0/1), zone, x, y, instance (0/1),
                               uiMapID, { x1, y1, x2, y2, ... } }   (x, y in 0.1% of the zone map)
"""
import os

from classicdb import ClassicDB

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "DropIndex.lua")
MIN_PCT = 1.0
MAX_PCT = 95.0
MIN_SPAWNS = 3
SKIP_RANKS = {2, 3, 4}   # rare elite, boss, rare
FACTION_NPC = {1, 2}     # Alliance- or Horde-friendly (guards, townsfolk)
SKIP_ZONES = {"Alterac Valley", "Warsong Gulch", "Arathi Basin"}


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    db = ClassicDB()
    items, used_npcs = {}, set()
    for iid, srcs in db.drops.items():
        it = db.items.get(iid)
        if not it or it.get("src") != "client" or it["bind"] not in (0, 2) or it["quality"] == 0:
            continue
        keep = []
        for nid, pct in sorted(srcs.items(), key=lambda kv: -kv[1]):
            n = db.npcs.get(nid)
            if not n or pct < MIN_PCT or pct >= MAX_PCT or pct == 80.0:
                continue  # >=95% / exactly 80% are vendor stock or quest-objective artefacts
            if n["rank"] in SKIP_RANKS or n["side"] in FACTION_NPC or n["max"] > 60:
                continue
            if len(n["spawns"]) < MIN_SPAWNS:
                continue  # unique named NPCs can't be farmed
            zone, _, _, inst = db.npc_location(nid)
            if inst or not zone or zone in SKIP_ZONES:
                continue
            keep.append((nid, pct))
        if keep:
            items[iid] = (it, keep[:6])
            used_npcs.update(nid for nid, _ in keep[:6])

    lines = ["-- Generated by tools/build_drops.py. Do not edit by hand.",
             "-- Drop sources from CMaNGOS classic-db and Wowhead (via ForeverPath_ClassicDB and QuestieDB);",
             "-- item names from the WoW Forever client tables (via ForeverPath).",
             "local _, ns = ...",
             "ns.drops = { items = {"]
    for iid in sorted(items):
        it, keep = items[iid]
        src = ",".join(f"{nid},{round(pct * 100)}" for nid, pct in keep)
        lines.append(f"[{iid}]={{{q(it['name'])},{it['quality']},{src}}},")
    lines.append("}, npcs = {")
    for nid in sorted(used_npcs):
        n = db.npcs[nid]
        zone, x, y, inst = db.npc_location(nid)
        elite = 1 if n["rank"] == 1 else 0
        mp, pts = db.spawn_points([nid])
        pts_lua = ",".join(f"{px},{py}" for px, py in pts)
        lines.append(f"[{nid}]={{{q(n['name'])},{n['min']},{n['max']},{elite},{q(zone or '?')},"
                     f"{x if x is not None else 'nil'},{y if y is not None else 'nil'},{1 if inst else 0},"
                     f"{mp if mp and mp > 0 else 'nil'},{{{pts_lua}}}}},")
    lines.append("} }")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT}: {len(items)} items, {len(used_npcs)} mobs, {os.path.getsize(OUT) // 1024} KB")


if __name__ == "__main__":
    main()
